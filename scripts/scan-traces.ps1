# scan-traces.ps1 - list candidate "who actually wrote this" traces in a repo.
# Report only: never edits, never deletes. Every hit must be judged by a human/agent,
# because cursor / agent / AI are common words with legitimate uses.
#
# Usage:
#   & '<skill dir>\scripts\scan-traces.ps1' -Repo 'C:\path\to\repo'
#   & '<skill dir>\scripts\scan-traces.ps1' -Repo 'C:\path\to\repo' -Quiet
#
# Note on paths: drive-letter paths are matched by regex, not by literal 'D:\'.
# A literal would also hit 'name:\s*' and 'file://' because -like is case-insensitive.

param(
    [Parameter(Mandatory = $true)][string]$Repo,
    [switch]$Quiet,
    [string]$Git = 'C:\Program Files\Git\cmd\git.exe'
)

if (-not (Test-Path -LiteralPath $Repo)) {
    Write-Output "FAILED: repo path not found: $Repo"
    exit 1
}
Set-Location -LiteralPath $Repo

# Only tracked files when this is a git repo - bin/obj and scratch files never ship.
$isRepo = $false
& $Git rev-parse --git-dir *> $null
if ($LASTEXITCODE -eq 0) { $isRepo = $true }

if ($isRepo) {
    $files = & $Git ls-files
}
else {
    $files = Get-ChildItem -LiteralPath $Repo -Recurse -File -Force |
        ForEach-Object { $_.FullName.Substring($Repo.TrimEnd('\').Length + 1) }
}

$skipExt = @('.png', '.jpg', '.jpeg', '.gif', '.ico', '.bmp', '.dll', '.exe', '.zip',
             '.7z', '.pdf', '.woff', '.woff2', '.ttf', '.otf', '.mp4', '.wav', '.pdb', '.snk')

# Category -> literal phrases. Keep them narrow and specific.
$categories = [ordered]@{
    'generation-stamp' = @(
        'Generated with', 'Generated by AI', 'AI-generated', 'Co-Authored-By',
        '可能由 AI 生成', '由 AI 生成', '由AI生成', '本文由 AI', 'AI 辅助生成'
    )
    'agent-voice' = @(
        '下一个接手', '本次任务', '已为你', '本机凭据', '本机 GCM',
        'this machine', 'your machine', 'as an AI', 'the assistant'
    )
    'ai-as-reason' = @(
        '交给 AI', '交给AI', '让 AI 分析', '让AI分析', 'AI 帮我写'
    )
    'tool-config' = @(
        'CLAUDE.md', '.cursorrules', 'copilot-instructions', '.mcp.json', 'AGENTS.md'
    )
}

# Absolute drive path with at least two segments: C:\Users\me\..., D:\DSH\workspace\...
# Two segments are required so that placeholders such as 'D:\…' and 'e:\s' do not match.
$pathRegex = '(?i)(?<![A-Za-z])[A-Z]:[\\/][A-Za-z0-9_.\-]+[\\/]'

$allLiterals = @()
foreach ($k in $categories.Keys) { $allLiterals += $categories[$k] }
$allLiterals = $allLiterals | Sort-Object -Unique

$hits = New-Object System.Collections.Generic.List[object]

foreach ($rel in $files) {
    $ext = [IO.Path]::GetExtension($rel).ToLowerInvariant()
    if ($skipExt -contains $ext) { continue }
    $full = Join-Path $Repo $rel
    if (-not (Test-Path -LiteralPath $full)) { continue }
    if ((Get-Item -LiteralPath $full).Length -gt 2MB) { continue }

    # File-name level traces: tool config files that should not be published at all.
    if ($rel -match '(?i)(CLAUDE\.md|\.cursorrules|\.claude[\\/]|copilot-instructions|\.mcp\.json|AGENTS\.md|\.aider)') {
        $hits.Add([pscustomobject]@{ Category = 'tool-config-file'; File = $rel; Line = 0; Text = '(whole file)' })
        continue
    }

    $lines = Select-String -LiteralPath $full -Pattern $allLiterals -SimpleMatch -ErrorAction SilentlyContinue
    foreach ($h in $lines) {
        $cat = 'other'
        foreach ($k in $categories.Keys) {
            foreach ($p in $categories[$k]) {
                if ($h.Line.IndexOf($p, [StringComparison]::OrdinalIgnoreCase) -ge 0) { $cat = $k; break }
            }
            if ($cat -ne 'other') { break }
        }
        $text = $h.Line.Trim()
        if ($text.Length -gt 140) { $text = $text.Substring(0, 140) + ' ...' }
        $hits.Add([pscustomobject]@{ Category = $cat; File = $rel; Line = $h.LineNumber; Text = $text })
    }

    $pathLines = Select-String -LiteralPath $full -Pattern $pathRegex -ErrorAction SilentlyContinue
    foreach ($h in $pathLines) {
        $text = $h.Line.Trim()
        if ($text.Length -gt 140) { $text = $text.Substring(0, 140) + ' ...' }
        $hits.Add([pscustomobject]@{ Category = 'private-path'; File = $rel; Line = $h.LineNumber; Text = $text })
    }
}

$hits = $hits | Sort-Object File, Line

if ($hits.Count -eq 0) {
    Write-Output 'clean: no candidate traces found'
    exit 0
}

Write-Output "candidates: $($hits.Count) in $(($hits | Select-Object -ExpandProperty File -Unique).Count) file(s)"
Write-Output 'Each hit is a CANDIDATE. Judge it: real trace, or legitimate use of cursor / agent / AI?'
Write-Output ''

foreach ($h in $hits) {
    Write-Output ("[{0}] {1}:{2}" -f $h.Category, $h.File, $h.Line)
    if (-not $Quiet) { Write-Output ("    " + $h.Text) }
}

Write-Output ''
Write-Output 'Reminder:'
Write-Output '  - delete footnotes such as generation stamps; do not leave the blank line behind'
Write-Output '  - rewrite machine-voice sentences in a person''s voice, keep the meaning'
Write-Output '  - replace private absolute paths with placeholders'
Write-Output '  - removing a doc means also clearing its README / tree / changelog references'
Write-Output '  - the commit message must never mention cleaning traces'
