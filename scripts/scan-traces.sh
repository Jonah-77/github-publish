#!/usr/bin/env bash
# scan-traces.sh -- list candidate "who actually wrote this" traces in a repo.
# Report only: never edits, never deletes. Every hit must be judged by a human/agent,
# because cursor / agent / AI are common words with legitimate uses.
#
# Usage:
#   ./scan-traces.sh --repo /path/to/repo
#   ./scan-traces.sh --repo /path/to/repo --quiet
#   ./scan-traces.sh --repo /path/to/repo --git /usr/bin/git
#
# Tool path: --git, or GIT_BIN, or the first git on PATH.
# Requires bash 4+ (uses case-insensitive parameter expansion). Runs as-is in Termux.

set -u

REPO=''
QUIET=0
GIT_ARG=''

while [ $# -gt 0 ]; do
    case "$1" in
        --repo)  REPO="${2:-}"; shift 2 ;;
        --git)   GIT_ARG="${2:-}"; shift 2 ;;
        --quiet) QUIET=1; shift ;;
        -h|--help) sed -n '2,12p' "$0"; exit 0 ;;
        *) echo "unknown argument: $1" >&2; exit 1 ;;
    esac
done

if [ -z "$REPO" ]; then echo "FAILED: --repo is required" >&2; exit 1; fi
if [ ! -d "$REPO" ]; then echo "FAILED: repo path not found: $REPO"; exit 1; fi

GIT="$GIT_ARG"
if [ -z "$GIT" ]; then GIT="${GIT_BIN:-}"; fi
if [ -z "$GIT" ]; then GIT="$(command -v git 2>/dev/null || true)"; fi
if [ -z "$GIT" ]; then echo "FAILED: git not found; pass --git or set GIT_BIN" >&2; exit 1; fi

cd "$REPO" || exit 1

# Only tracked files when this is a git repo: bin/obj and scratch files never ship.
IS_REPO=0
if "$GIT" rev-parse --git-dir >/dev/null 2>&1; then IS_REPO=1; fi

TMP="$(mktemp -d 2>/dev/null || mktemp -d -t traces)"
trap 'rm -rf "$TMP"' EXIT

if [ "$IS_REPO" -eq 1 ]; then
    "$GIT" ls-files > "$TMP/files"
else
    find . -type f -print 2>/dev/null | sed 's|^\./||' > "$TMP/files"
fi

# category<TAB>literal -- keep the phrases narrow and specific.
cat > "$TMP/cats" <<'CATS'
generation-stamp	Generated with
generation-stamp	Generated by AI
generation-stamp	AI-generated
generation-stamp	Co-Authored-By
generation-stamp	可能由 AI 生成
generation-stamp	由 AI 生成
generation-stamp	由AI生成
generation-stamp	本文由 AI
generation-stamp	AI 辅助生成
agent-voice	下一个接手
agent-voice	本次任务
agent-voice	已为你
agent-voice	本机凭据
agent-voice	本机 GCM
agent-voice	this machine
agent-voice	your machine
agent-voice	as an AI
agent-voice	the assistant
ai-as-reason	交给 AI
ai-as-reason	交给AI
ai-as-reason	让 AI 分析
ai-as-reason	让AI分析
ai-as-reason	AI 帮我写
tool-config	CLAUDE.md
tool-config	.cursorrules
tool-config	copilot-instructions
tool-config	.mcp.json
tool-config	AGENTS.md
CATS

cut -f2- "$TMP/cats" | sort -u > "$TMP/literals"

# Absolute drive path with at least two segments, plus POSIX home paths.
# Two segments are required so placeholders such as 'D:\...' and 'e:\s' do not match.
PATH_RE='(^|[^A-Za-z])[A-Za-z]:[\\/][A-Za-z0-9_.-]+[\\/]|(^|[^A-Za-z])/(home|Users)/[A-Za-z0-9_.-]+/'

: > "$TMP/hits"

classify() {
    local text="$1" cat lit lower
    lower="${text,,}"
    while IFS=$'\t' read -r cat lit; do
        [ -n "$cat" ] || continue
        if [[ "$lower" == *"${lit,,}"* ]]; then
            printf '%s' "$cat"
            return 0
        fi
    done < "$TMP/cats"
    printf 'other'
}

while IFS= read -r rel; do
    [ -n "$rel" ] || continue
    case "$rel" in *.png|*.jpg|*.jpeg|*.gif|*.ico|*.bmp|*.dll|*.exe|*.zip|*.7z|*.pdf|*.woff|*.woff2|*.ttf|*.otf|*.mp4|*.wav|*.pdb|*.snk) continue ;; esac
    [ -f "$rel" ] || continue

    # File-name level traces: tool config files that should not be published at all.
    case "$rel" in
        CLAUDE.md|*"/CLAUDE.md"|.cursorrules|*"/.cursorrules"|.mcp.json|*"/.mcp.json"|AGENTS.md|*"/AGENTS.md"|.claude/*|*"/.claude/"*|*copilot-instructions*|*.aider)
            printf '%s\t0\ttool-config-file\t(whole file)\n' "$rel" >> "$TMP/hits"
            continue ;;
    esac

    [ "$(wc -c < "$rel" 2>/dev/null || echo 0)" -gt 2097152 ] && continue

    while IFS= read -r hit; do
        [ -n "$hit" ] || continue
        lineno="${hit%%:*}"
        text="${hit#*:}"
        text="${text#"${text%%[![:space:]]*}"}"
        [ "${#text}" -gt 140 ] && text="${text:0:140} ..."
        printf '%s\t%s\t%s\t%s\n' "$rel" "$lineno" "$(classify "$text")" "$text" >> "$TMP/hits"
    done < <(grep -F -in -f "$TMP/literals" -- "$rel" 2>/dev/null || true)

    while IFS= read -r hit; do
        [ -n "$hit" ] || continue
        lineno="${hit%%:*}"
        line="${hit#*:}"
        # documentation placeholders (C:\Users\<me>\ ...) are not private paths:
        # strip <...> and re-test, so only real absolute paths become candidates.
        if ! printf '%s' "$line" | sed -E 's/C:\\Users\\<[^>]*>//g; s/<[^>]*>//g' | grep -E -q -- "$PATH_RE"; then
            continue
        fi
        text="${line#"${line%%[![:space:]]*}"}"
        [ "${#text}" -gt 140 ] && text="${text:0:140} ..."
        printf '%s\t%s\t%s\t%s\n' "$rel" "$lineno" "private-path" "$text" >> "$TMP/hits"
    done < <(grep -E -in "$PATH_RE" "$rel" 2>/dev/null || true)
done < "$TMP/files"

sort -t $'\t' -k1,1 -k2,2n "$TMP/hits" > "$TMP/sorted"
COUNT="$(wc -l < "$TMP/sorted" | tr -d ' ')"
FILES="$(cut -f1 "$TMP/sorted" | sort -u | wc -l | tr -d ' ')"

if [ "$COUNT" -eq 0 ]; then
    echo 'clean: no candidate traces found'
    exit 0
fi

echo "candidates: $COUNT in $FILES file(s)"
echo 'Each hit is a CANDIDATE. Judge it: real trace, or legitimate use of cursor / agent / AI?'
echo ''
while IFS=$'\t' read -r file line cat text; do
    printf '[%s] %s:%s\n' "$cat" "$file" "$line"
    if [ "$QUIET" -eq 0 ]; then printf '    %s\n' "$text"; fi
done < "$TMP/sorted"

echo ''
echo 'Reminder:'
echo '  - delete footnotes such as generation stamps; do not leave the blank line behind'
echo "  - rewrite machine-voice sentences in a person's voice, keep the meaning"
echo '  - replace private absolute paths with placeholders'
echo '  - removing a doc means also clearing its README / tree / changelog references'
echo '  - the commit message must never mention cleaning traces'
exit 0
